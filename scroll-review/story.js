function scene(topic, index, title, explanation, options = {}) {
  const step = topics[topic].steps[index];
  const name = options.altered ? step.changed : step.image;
  const asset = step.external
    ? 'review/vascular/assets/microvascular.webp'
    : `review/mechanisms/assets/${name}.webp`;
  return { mode: step.mode, asset, title, explanation, ...options };
}

